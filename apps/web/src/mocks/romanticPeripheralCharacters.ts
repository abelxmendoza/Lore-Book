import type { Character } from '../components/characters/CharacterProfileCard';

function peripheralCharacter(
  partial: Pick<Character, 'id' | 'name' | 'role' | 'summary'> &
    Partial<Character> & {
      anchorName: string;
      peripheralId: string;
      tier: 'suspected' | 'confirmed';
    },
): Character {
  const {
    anchorName,
    peripheralId,
    tier,
    id,
    name,
    role,
    summary,
    ...rest
  } = partial;
  return {
    id,
    name,
    first_name: name.split(' ')[0] ?? name,
    last_name: null,
    alias: [name],
    pronouns: rest.pronouns ?? 'they/them',
    archetype: 'romantic',
    role,
    status: 'active',
    importance_level: 'background',
    importance_score: tier === 'confirmed' ? 22 : 16,
    is_nickname: false,
    proximity_level: 'third_party',
    has_met: false,
    relationship_depth: 'mentioned_only',
    likelihood_to_meet: 'unlikely',
    context_of_mention: `Attributed to ${anchorName} via Dating & Romance periphery`,
    associated_with_character_ids: rest.associated_with_character_ids ?? [],
    summary,
    tags: ['romantic-peripheral', tier, 'unmet'],
    metadata: {
      relationship_type: 'romantic_peripheral',
      source: 'romantic_peripheral',
      peripheral_id: peripheralId,
      tier,
      closeness_score: 0,
      autoGenerated: true,
    },
    social_media: {},
    memory_count: 1,
    relationship_count: 0,
    ...rest,
  };
}

