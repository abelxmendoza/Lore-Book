const BY_ID = new Map(
  [...MOCK_ROMANTIC_CAST_CHARACTERS, ...MOCK_ROMANTIC_PERIPHERAL_CHARACTERS].map((c) => [c.id, c]),
);

export function getMockRomanticPeripheralCharacters(): Character[] {
  return [...MOCK_ROMANTIC_CAST_CHARACTERS, ...MOCK_ROMANTIC_PERIPHERAL_CHARACTERS];
}

export function getMockRomanticBookCharacterById(id: string): Character | undefined {
  return BY_ID.get(id);
}

/** Merge demo romantic periphery/cast into a Character Book list without duplicates. */
export function mergeRomanticDemoCharacters(base: Character[]): Character[] {
  const byId = new Map(base.map((c) => [c.id, c]));
  for (const c of getMockRomanticPeripheralCharacters()) {
    if (!byId.has(c.id)) byId.set(c.id, c);
  }
  return [...byId.values()];
}
